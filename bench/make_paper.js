#!/usr/bin/env node
/* Build the paper draft (Markdown) from benchmark results.
 *
 *   node bench/make_paper.js [results.json] [out.md] ["Author"] ["Affiliation"] ["email"]
 *
 * Defaults: data/results.json -> docs/paper-draft.md
 * Every number in the draft comes from the results file (see js/paper.js).
 * Also prints a short plain-language summary of the main comparison.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const C = require(path.join(root, 'js', 'mayor.js'));
const P = require(path.join(root, 'js', 'paper.js'));

const inFile = path.resolve(process.argv[2] || path.join(root, 'data', 'results.json'));
const outFile = path.resolve(process.argv[3] || path.join(root, 'docs', 'paper-draft.md'));
const res = JSON.parse(fs.readFileSync(inFile, 'utf8'));

const md = P.buildPaper(res, {
  author: process.argv[4] || undefined,
  affiliation: process.argv[5] || undefined,
  email: process.argv[6] || undefined,
  actions: C.ACTIONS,
});
/* The method text in js/paper.js is a fixed template. Say so at the top, so nobody
   mistakes the draft for a finished paper or for a description of files that are not here. */
const NOTE = [
  '> **Read this first.** This draft was generated by `bench/make_paper.js` from `' + path.relative(root, inFile).replace(/\\/g, '/') + '`.',
  '> All numbers and tables come from those runs. The surrounding text is a fixed template in `js/paper.js`:',
  '> parts of it describe an earlier version of the agent team (four officers and six pressures; the code now has',
  '> seven officers and nine), and it mentions A/B and red-team scripts and results that are **not** in this repository.',
  '> Check every sentence, number and reference before sharing it.',
  '', '',
].join('\n');
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, NOTE + md);

const A = P.analyse(res);
const has = (c) => Object.keys(res.meta.controllers).includes(c);
if (has('consent') && has('none')) {
  const t = A.cmp('consent', 'none', 'C').pooled;
  const f = (v) => (v * 100).toFixed(1);
  console.log(`Agent team with consent against no intervention, total cost: mean paired difference ${f(t.mean)} points ` +
    `(95% CI ${f(t.lo)} to ${f(t.hi)}), better in ${t.wins} of ${t.n} paired runs. Positive = agents better.`);
}
console.log(`Wrote ${md.split(/\s+/).length} words to ${path.relative(process.cwd(), outFile)}.`);
